"""Generate the [PROPOSED] message schemas from config/schema.toml.

Usage:
    py schema/build.py           write schema/*.schema.json and harness_api/messages.py
    py schema/build.py --check   exit 1 if any file is out of date

The generated files are what participants and the engine use: the JSON Schemas, and the
Pydantic models the harness methods receive and return. Change the settings in
config/schema.toml, not the generated files.
"""

from __future__ import annotations

import json
import re
import string
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG_PATH = ROOT / "config" / "schema.toml"
SCHEMA_DIR = ROOT / "schema"

DRAFT = "https://json-schema.org/draft/2020-12/schema"
ID_PATTERN = re.compile(r"^[a-z][a-z0-9_]*$")
RESERVED_IDS = {"none", "all", "event", "you"}
HEADER = "Generated by schema/build.py from config/schema.toml. Do not edit by hand."


def load_config(path: Path = CONFIG_PATH) -> dict:
    """Read and check the config, so a bad edit fails loudly here."""
    cfg = tomllib.loads(path.read_text(encoding="utf-8"))

    classes = cfg["classes"]
    assert classes, "at least one class is required"
    for cid in classes:
        assert ID_PATTERN.match(cid), f"bad class id {cid!r}"
        assert cid not in RESERVED_IDS, f"class id {cid!r} is reserved"
    players = cfg["run"]["players_per_run"]
    assert players == len(classes), "players_per_run must equal the number of classes"

    stats = cfg["stats"]
    names = stats["names"]
    assert names and len(set(names)) == len(names), "stat names must be unique"
    for name in names:
        assert ID_PATTERN.match(name), f"bad stat name {name!r}"
    if "maximum" in stats:
        assert stats["maximum"] >= stats["minimum"], "stat maximum is below minimum"

    for section in ("player_text", "gm_text"):
        for key, value in cfg[section].items():
            assert isinstance(value, int) and value > 0, f"{section}.{key} must be a positive integer"
    return cfg


def max_words_pattern(n: int) -> str:
    """At least one and at most n whitespace-separated words."""
    return rf"^\s*\S+(\s+\S+){{0,{n - 1}}}\s*$"


def build_action(cfg: dict) -> dict:
    classes = list(cfg["classes"])
    pt = cfg["player_text"]
    free_text = {
        "description": (
            f'Open-ended free text, e.g. "seduce the giant". [DECIDED] Limited to {pt["max_words"]} words '
            f'and {pt["max_chars"]} characters. Longer text is not invalid: the engine (not the GM) cuts it off '
            f'at the {pt["max_chars"]}th character, then after the {pt["max_words"]}th word, with no penalty '
            ". [PROPOSED] A word is a run of non-whitespace characters. "
            "This schema describes the message after the engine's cuts."
        ),
        "type": "string",
        "pattern": r"\S",
        "maxLength": pt["max_chars"],
    }
    return {
        "$schema": DRAFT,
        "$comment": HEADER,
        "title": "Action",
        "description": (
            "[PROPOSED] The one action a harness submits each round. "
            "It targets either the current event or one other player, never both. Self-contained so it "
            "can be turned into a generation grammar directly. The field names are a proposal; the action "
            "schema is still open."
        ),
        "oneOf": [
            {
                "title": "Event-directed action",
                "type": "object",
                "additionalProperties": False,
                "required": ["target", "action"],
                "properties": {
                    "target": {"const": "event"},
                    "action": {"$ref": "#/$defs/free_text"},
                },
            },
            {
                "title": "Player-directed interaction (positive only)",
                "type": "object",
                "additionalProperties": False,
                "required": ["target", "target_class", "action"],
                "$comment": "DECIDED 2026-11-04: no interaction field. Each class has one positive interaction, its support ability (content/characters.toml), which the engine applies.",
                "properties": {
                    "target": {"const": "player"},
                    "target_class": {
                        "description": "Class of the player receiving the interaction.",
                        "enum": classes,
                    },
                    "action": {"$ref": "#/$defs/free_text"},
                },
            },
        ],
        "$defs": {"free_text": free_text},
    }


def build_broadcast(cfg: dict) -> dict:
    pt = cfg["player_text"]
    return {
        "$schema": DRAFT,
        "$comment": HEADER,
        "title": "Broadcast",
        "description": (
            "[PROPOSED] The optional message a harness submits in the broadcast window. "
            '"none" means no message and carries no text; "all" or a class must carry non-empty text. '
            "The GM announces the text word for word. An invalid broadcast is dropped, as if no message "
            "had been sent. Self-contained so it can be turned into a generation grammar directly. "
            "The spec's [None], [all] and [class] map to \"none\", \"all\" and a class id."
        ),
        "oneOf": [
            {
                "title": "No message",
                "type": "object",
                "additionalProperties": False,
                "required": ["to"],
                "properties": {"to": {"const": "none"}},
            },
            {
                "title": "Message to everyone or to one class",
                "type": "object",
                "additionalProperties": False,
                "required": ["to", "text"],
                "properties": {
                    "to": {
                        "description": '"all", or the class of the single recipient.',
                        "enum": ["all", *cfg["classes"]],
                    },
                    "text": {
                        "description": (
                            f"[DECIDED] Same limits as action text: the engine (not the GM) cuts longer text off at the "
                            f'{pt["max_chars"]}th character, then after the {pt["max_words"]}th word, with no penalty '
                            ". This schema describes the message after those cuts."
                        ),
                        "type": "string",
                        "pattern": r"\S",
                        "maxLength": pt["max_chars"],
                    },
                },
            },
        ],
    }


