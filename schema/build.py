def build_limits(cfg: dict, rules_path: Path = RULES_PATH) -> str:
    rules = tomllib.loads(rules_path.read_text(encoding="utf-8"))
    t = rules["timeouts"]
    orch = tomllib.loads(ORCH_PATH.read_text(encoding="utf-8"))
    return LIMITS_TEMPLATE.substitute(
        init=float(orch["windows"]["init_seconds"]),
        broadcast=float(t["broadcast_seconds"]),
        action=float(t["action_seconds"]),
        confirmation=float(t["confirmation_seconds"]),
        penalty=rules["combat"]["player"]["penalty_invalid_action"],
        max_words=cfg["player_text"]["max_words"],
        max_chars=cfg["player_text"]["max_chars"],
    )


def generated_files(cfg: dict) -> dict[Path, str]:
    """Every generated file: the JSON Schemas, the Pydantic models and the time limits."""
    files = {SCHEMA_DIR / name: text for name, text in build_all(cfg).items()}
    files[MODELS_PATH] = build_models(cfg)
    files[LIMITS_PATH] = build_limits(cfg)
    return files


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, text in generated_files(load_config()).items():
        filename = str(path.relative_to(ROOT))
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            stale.append(filename)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("out of date (run py schema/build.py): " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
